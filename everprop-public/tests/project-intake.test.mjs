import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';

const output = ts.transpileModule(fs.readFileSync(new URL('../src/lib/project-intake.ts', import.meta.url), 'utf8'),
  { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {} };
vm.runInNewContext(output, context);
const { intakePayload, intakeBasics, emptyIntakeBasics } = context.exports;
const base = { ...emptyIntakeBasics, name: ' Proyecto real ', city: 'Yala', province: 'Jujuy', project_type: 'BUILDING' };

test('unknown commercial values stay unknown and no units are generated by the payload', () => {
  const data = intakePayload(base);
  assert.equal(data.name, 'Proyecto real');
  assert.equal(data.status, 'UNKNOWN');
  assert.equal(data.progress, null);
  assert.equal(data.total_units, 0);
  assert.equal('units' in data, false);
  assert.equal('is_visible' in data, false);
  assert.equal('tenant_id' in data, false);
});

test('rejects incomplete basics and invalid numeric input before sending a request', () => {
  for (const patch of [{ name: ' ' }, { city: '' }, { province: '' }, { project_type: '' }, { progress: '-1' }, { progress: '101' }, { total_units: '2.5' }, { total_units: '9007199254740992' }]) {
    assert.throws(() => intakePayload({ ...base, ...patch }));
  }
  assert.equal(intakePayload({ ...base, progress: '0', total_units: '12' }).progress, 0);
  assert.equal(intakePayload({ ...base, progress: '100' }).progress, 100);
});

test('reopening a saved project preserves real values and distinguishes zero progress from unknown', () => {
  const project = { public_id: 'uuid', ...intakePayload(base), progress: 0, properties_count: 0 };
  assert.equal(intakeBasics(project).progress, '0');
  assert.equal(intakeBasics({ ...project, progress: null }).progress, '');
  assert.equal(intakeBasics({ ...project, total_units: 30 }).total_units, '30');
});
