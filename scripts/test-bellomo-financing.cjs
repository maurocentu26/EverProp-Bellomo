const fs = require('node:fs');
const ts = require('../everprop-public/node_modules/typescript');
const assert = require('node:assert/strict');
const source = fs.readFileSync('everprop-public/src/lib/bellomo-financing.ts', 'utf8');
const out = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const moduleShim = { exports: {} };
new Function('exports', out)(moduleShim.exports);
const { FINANCING_PLANS: plans, financingSummary: summary, cacPayment: cac, findFinancingPlan: find } = moduleShim.exports;
assert.equal(plans.length, 15);
assert.equal(find('EL ROCIO').name, 'El Rocío');
assert.equal(find('Loteo San Pablo 1').name, 'San Pablo 1');
assert.equal(find('Valle Verde Loteo').name, 'Valle Verde');
assert.equal(find('Remanente El Roco'), undefined);
assert.equal(find('Proyecto sin condiciones'), undefined);
assert.equal(find('San Pablo 1').fixed.at(-1).max, 36);
assert.equal(find('San Pablo 2').fixed.at(-1).max, 48);
assert.equal(find('Las Colinas 2').fixed.at(-1).max, 72);
assert.equal(find('Los Arenales').cacMax, undefined);
const p = summary(find('San Pablo 1'), 20000000, true, 'ARS', 0);
assert.equal(p.net, 18000000); assert.equal(p.minimum, 5400000); assert.equal(p.balance, 12600000);
assert.equal(summary(find('El Rocío'), 20000, true, 'USD', 0).valid, false);
assert.equal(summary(find('El Rocío'), 20000, true, 'USD', 1000).minimum, 1500);
assert.equal(summary(find('El Rocío'), 20000000, true, 'ARS', 0, 100).valid, false);
assert.equal(summary(find('El Rocío'), 20000000, true, 'ARS', 0, 20000001).valid, false);
assert.equal(summary(find('El Rocío'), Infinity, true, 'ARS', 0), null);
assert.equal(cac(12600000, 48, 100, 110), 288750);
for (const args of [[100,0,100,110], [100,1.5,100,110], [100,48,0,110], [100,48,100,-1], [100,48,100,Infinity]]) assert.equal(cac(...args), null);
assert.equal(cac(0,48,100,110), 0);
console.log('Financing conditions and calculation checks passed');

const { fixedPayment } = moduleShim.exports;
assert.deepEqual(fixedPayment(12600000, 12, 3.5), { monthly: 1491000, interest: 5292000, total: 17892000 });
assert.deepEqual(fixedPayment(12600000, 36, 4), { monthly: 854000, interest: 18144000, total: 30744000 });
assert.deepEqual(fixedPayment(120000, 12, 0), { monthly: 10000, interest: 0, total: 120000 });
for (const args of [[100,0,4], [100,1.5,4], [100,12,-1], [Infinity,12,4]]) assert.equal(fixedPayment(...args), null);
console.log('Confirmed fixed-interest formula checks passed');
